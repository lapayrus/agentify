//! The Compose file a Project's distro runs.
//!
//! The daemon hands a Backend an [`EnvironmentSpec`] and nothing else: no YAML,
//! no Compose knowledge, no container names. This module turns that spec into the
//! one document `docker compose` understands, so the WSL adapter can start real
//! workloads without the daemon learning anything about containers.
//!
//! Four decisions are worth stating where they live:
//!
//! * **Leases are published on loopback only.** Each declared port gets a
//!   `127.0.0.1:<host>:<guest>` mapping, so the daemon's probe reaches the
//!   container through the leased port and nothing is exposed beyond loopback.
//!   A stopped container cannot leave a port answering, and two Projects cannot
//!   fight over 5432 inside their own distros.
//! * **`engine` + `version` map to an image here**, once, so a Manifest says
//!   `postgres`/`16` and never a registry path. The `-alpine` variants are used
//!   because the pull happens inside a per-Project distro: the same database,
//!   half the bytes, on every Project that starts.
//! * **`dependsOn` becomes `condition: service_healthy`** when the dependency
//!   declares a healthcheck, which is what makes the app wait for Postgres
//!   instead of dying against a socket that is not listening yet.
//! * **Volumes are pinned by name** (`name: <project>-<resource>-data`). Compose
//!   would otherwise prefix the volume with its own project name, and the
//!   daemon's naming contract — a volume the daemon can name and later delete —
//!   would quietly stop holding.

use std::collections::BTreeMap;

use serde_json::{Map, Value};

use crate::error::{BackendError, Result};
use crate::spec::{EnvironmentSpec, ResourceSpec};

use super::cli::Wsl;

/// Directory inside the distro that holds the Project's generated runtime
/// files. Daemon-owned: nothing else writes here.
pub const RUNTIME_DIR: &str = "/srv/agentify";
/// The Project's source, copied in from the daemon-owned workspace.
pub const PROJECT_DIR: &str = "/srv/agentify/project";
/// The generated Compose file.
pub const COMPOSE_PATH: &str = "/srv/agentify/compose.yaml";
/// The Compose project name, so network names are stable and recognisable.
pub const COMPOSE_PROJECT: &str = "agentify";

/// Where a Postgres image keeps its data, for a named volume.
pub const POSTGRES_DATA_DIR: &str = "/var/lib/postgresql/data";

/// One leased port, paired with the Compose service that answers on it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Relay {
    /// The Compose service name: the Resource's name.
    pub service: String,
    /// The port the container listens on.
    pub guest_port: u16,
    /// The leased host port the supervisor binds and relays.
    pub host_port: u16,
}

impl Relay {
    /// `service:guest:host`, the token the supervisor is started with. Both
    /// halves are generated by this repository, so the shape is a contract
    /// between two languages, and [`tests::a_relay_token_is_parseable`] pins it.
    pub fn token(&self) -> String {
        format!("{}:{}:{}", self.service, self.guest_port, self.host_port)
    }
}

/// The relays for a spec: one per lease, in a stable order.
pub fn relays(spec: &EnvironmentSpec) -> Vec<Relay> {
    let mut relays: Vec<Relay> = spec
        .ports
        .iter()
        .filter(|lease| {
            spec.resources
                .iter()
                .any(|resource| resource.name == lease.resource)
        })
        .map(|lease| Relay {
            service: lease.resource.clone(),
            guest_port: lease.guest_port,
            host_port: lease.host_port,
        })
        .collect();
    relays.sort_by(|left, right| (left.service.as_str(), left.guest_port).cmp(&(right.service.as_str(), right.guest_port)));
    relays.dedup_by(|left, right| left.service == right.service && left.guest_port == right.guest_port);
    relays
}

/// The image an `engine` + `version` pair names.
pub fn image_for(resource: &ResourceSpec) -> Result<String> {
    match resource.engine.as_deref() {
        Some("postgres") => {
            let version = resource
                .version
                .as_deref()
                .map(str::trim)
                .filter(|version| !version.is_empty())
                .unwrap_or("16");
            // A version is a tag, not a free-form string: refuse anything that
            // could change the reference into another repository or digest.
            if !version
                .chars()
                .all(|character| character.is_ascii_alphanumeric() || character == '.' || character == '-')
            {
                return Err(BackendError::ExecutionFailed {
                    code: 2,
                    detail: format!(
                        "Resource {:?} declares engine postgres with version {version:?}, which is not an image tag",
                        resource.name
                    ),
                });
            }
            Ok(format!("postgres:{version}-alpine"))
        }
        Some(other) => Err(BackendError::Unsupported {
            capability: format!("engine {other}"),
            detail: format!(
                "Resource {:?} asks for the database engine {other:?}; v0 runs postgres",
                resource.name
            ),
        }),
        None => Err(BackendError::ExecutionFailed {
            code: 2,
            detail: format!("database Resource {:?} declares no engine", resource.name),
        }),
    }
}

/// The volume a database Resource's data lives in: the Manifest's name when it
/// pinned one, otherwise the daemon's generated `<project>-<resource>-data`.
pub fn volume_name(project: &str, resource: &ResourceSpec) -> String {
    match resource.volume.as_deref().map(str::trim) {
        Some(pinned) if !pinned.is_empty() => pinned.to_string(),
        _ => format!("{project}-{}-data", resource.name),
    }
}

/// The whole Compose document, ready to write into the distro.
pub fn compose_document(spec: &EnvironmentSpec) -> Result<Value> {
    let mut services = Map::new();
    let mut volumes = Map::new();

    let leases = relays(spec);
    for resource in &spec.resources {
        let mut service = service_document(spec, resource, &mut volumes)?;
        let mappings: Vec<Value> = leases
            .iter()
            .filter(|lease| lease.service == resource.name)
            .map(|lease| {
                Value::String(format!(
                    "127.0.0.1:{}:{}",
                    lease.host_port, lease.guest_port
                ))
            })
            .collect();
        if !mappings.is_empty() {
            if let Some(object) = service.as_object_mut() {
                object.insert("ports".to_string(), Value::Array(mappings));
            }
        }
        services.insert(resource.name.clone(), service);
    }
    if services.is_empty() {
        return Err(BackendError::ExecutionFailed {
            code: 2,
            detail: format!(
                "Environment {} declares no Resource to run",
                spec.environment_id
            ),
        });
    }

    let mut document = Map::new();
    document.insert("services".to_string(), Value::Object(services));
    if !volumes.is_empty() {
        document.insert("volumes".to_string(), Value::Object(volumes));
    }
    Ok(Value::Object(document))
}

/// The Compose document as YAML.
pub fn compose_yaml(spec: &EnvironmentSpec) -> Result<String> {
    let document = compose_document(spec)?;
    serde_yaml_ng::to_string(&document).map_err(|err| BackendError::ExecutionFailed {
        code: 2,
        detail: format!("generating the Compose file failed: {err}"),
    })
}

fn service_document(
    spec: &EnvironmentSpec,
    resource: &ResourceSpec,
    volumes: &mut Map<String, Value>,
) -> Result<Value> {
    let mut service = Map::new();

    // Where the image comes from: a build in the Project's own context, a
    // database engine, or a plain image reference.
    if let Some(build) = &resource.build {
        let context = build_context(&build.context);
        let mut entry = Map::new();
        entry.insert("context".to_string(), Value::String(context));
        entry.insert("dockerfile".to_string(), Value::String(build.dockerfile.clone()));
        service.insert("build".to_string(), Value::Object(entry));
    } else if let Some(image) = resource.image.as_deref().map(str::trim).filter(|image| !image.is_empty()) {
        service.insert("image".to_string(), Value::String(image.to_string()));
    } else if resource.kind == "database" {
        service.insert("image".to_string(), Value::String(image_for(resource)?));
    } else {
        return Err(BackendError::ExecutionFailed {
            code: 2,
            detail: format!(
                "Resource {:?} declares neither `image` nor `build`",
                resource.name
            ),
        });
    }

    if !resource.command.is_empty() {
        service.insert(
            "command".to_string(),
            Value::Array(
                resource
                    .command
                    .iter()
                    .map(|part| Value::String(part.clone()))
                    .collect(),
            ),
        );
    }

    if !resource.env.is_empty() {
        let mut env = Map::new();
        let mut keys: Vec<&String> = resource.env.keys().collect();
        keys.sort();
        for key in keys {
            env.insert(key.clone(), Value::String(resource.env[key].clone()));
        }
        service.insert("environment".to_string(), Value::Object(env));
    }

    if let Some(volume) = data_volume(spec, resource) {
        volumes.insert(volume.clone(), {
            let mut entry = Map::new();
            entry.insert("name".to_string(), Value::String(volume.clone()));
            Value::Object(entry)
        });
        service.insert(
            "volumes".to_string(),
            Value::Array(vec![Value::String(format!("{volume}:{POSTGRES_DATA_DIR}"))]),
        );
    }

    if !resource.depends_on.is_empty() {
        let mut dependencies = Map::new();
        for dependency in &resource.depends_on {
            let healthy = spec
                .resource(dependency)
                .map(waits_for_readiness)
                .unwrap_or(false);
            let mut entry = Map::new();
            entry.insert(
                "condition".to_string(),
                Value::String(if healthy {
                    "service_healthy".to_string()
                } else {
                    "service_started".to_string()
                }),
            );
            dependencies.insert(dependency.clone(), Value::Object(entry));
        }
        service.insert("depends_on".to_string(), Value::Object(dependencies));
    }

    if let Some(healthcheck) = healthcheck_document(resource) {
        service.insert("healthcheck".to_string(), healthcheck);
    }

    // The Backend owns the restart policy: a container that dies is restarted
    // inside the runtime, and the daemon learns about it by probing the lease.
    service.insert(
        "restart".to_string(),
        Value::String("unless-stopped".to_string()),
    );

    Ok(Value::Object(service))
}

/// Whether waiting for this Resource means waiting for its healthcheck.
///
/// A database always gets one — [`healthcheck_document`] writes `pg_isready`,
/// whether or not the Manifest asked for a probe — and an app gets one only when
/// the Manifest declared it, because this module will not invent a shell inside
/// an arbitrary image.
fn waits_for_readiness(resource: &ResourceSpec) -> bool {
    resource.kind == "database" || resource.healthcheck.is_some()
}

/// The named volume a database Resource's data lives in, if it has one.
fn data_volume(spec: &EnvironmentSpec, resource: &ResourceSpec) -> Option<String> {
    if resource.kind != "database" {
        return None;
    }
    Some(volume_name(&spec.project, resource))
}

/// A readiness probe Compose can run for the Resource.
///
/// Only a database gets one, and it is the engine's own client: `pg_isready`
/// knows when Postgres accepts connections, which is exactly what an app that
/// `dependsOn` it needs. An app's declared healthcheck belongs to the daemon,
/// which owns the `environment.up` decision and probes the lease; guessing a
/// shell inside an arbitrary image here would be a second, weaker opinion.
fn healthcheck_document(resource: &ResourceSpec) -> Option<Value> {
    if resource.kind != "database" {
        return None;
    }
    let mut healthcheck = Map::new();
    healthcheck.insert(
        "test".to_string(),
        Value::Array(vec![
            Value::String("CMD-SHELL".to_string()),
            Value::String(
                // `$$` is Compose's escape: the container's shell expands the
                // variable, not the file's reader.
                "pg_isready -U \"$$POSTGRES_USER\" -d \"$$POSTGRES_USER\"".to_string(),
            ),
        ]),
    );
    healthcheck.insert(
        "interval".to_string(),
        Value::String(
            resource
                .healthcheck
                .as_ref()
                .map(|check| check.interval.clone())
                .unwrap_or_else(|| "5s".to_string()),
        ),
    );
    healthcheck.insert("timeout".to_string(), Value::String("5s".to_string()));
    healthcheck.insert("retries".to_string(), Value::from(30u32));
    // A first boot initialises the cluster, which on a slow machine takes
    // longer than one interval.
    healthcheck.insert("start_period".to_string(), Value::String("20s".to_string()));
    Some(Value::Object(healthcheck))
}

/// A build context inside the Project's own directory.
///
/// The Manifest's context is relative to the workspace, so it is resolved to an
/// absolute path inside the distro: `.` is the Project directory itself, and
/// anything that climbs is refused before it can name a directory the Project
/// was never given.
fn build_context(relative: &str) -> String {
    let trimmed = relative.trim().trim_start_matches("./");
    if trimmed.is_empty() || trimmed == "." {
        return PROJECT_DIR.to_string();
    }
    // The context stays inside the Project directory: no `..`, no absolute path,
    // for the same reason a copy does.
    let mut parts: Vec<&str> = Vec::new();
    for part in trimmed.split('/') {
        match part {
            "" | "." => continue,
            ".." => {
                parts.pop();
            }
            other => parts.push(other),
        }
    }
    if parts.is_empty() {
        PROJECT_DIR.to_string()
    } else {
        format!("{PROJECT_DIR}/{}", parts.join("/"))
    }
}

/// The environment the supervisor runs `docker compose` with.
pub fn compose_environment() -> BTreeMap<String, String> {
    BTreeMap::from([(
        "COMPOSE_PROJECT_NAME".to_string(),
        COMPOSE_PROJECT.to_string(),
    )])
}

/// Write the Project's source into the distro, one regular file at a time.
///
/// There is no host mount in v0 and no `\\wsl$` share: the files travel on the
/// launcher's pipes, base64 both ways, exactly as a `copyIn` does. A file that is
/// not a regular file — a symlink, a device, a directory tree that recurses — is
/// skipped rather than followed, so a workspace cannot reach outside itself.
pub fn push_workspace(wsl: &Wsl, distro: &str, spec: &EnvironmentSpec, root: Option<&std::path::Path>) -> Result<usize> {
    let workspace = &spec.workspace;
    if workspace.as_os_str().is_empty() {
        return Ok(0);
    }
    let mut written = 0;
    let mut pending = vec![(workspace.clone(), String::new())];
    let mut budget = 256;
    while let Some((directory, relative)) = pending.pop() {
        let entries = match std::fs::read_dir(&directory) {
            Ok(entries) => entries,
            Err(err) if relative.is_empty() => {
                return Err(BackendError::ExecutionFailed {
                    code: 1,
                    detail: format!("cannot read the workspace {}: {err}", directory.display()),
                })
            }
            Err(_) => continue,
        };
        for entry in entries.flatten() {
            budget -= 1;
            if budget == 0 {
                return Err(BackendError::ExecutionFailed {
                    code: 1,
                    detail: format!(
                        "the workspace {} has too many files to copy into the runtime",
                        workspace.display()
                    ),
                });
            }
            let name = entry.file_name().to_string_lossy().to_string();
            let child = if relative.is_empty() {
                name.clone()
            } else {
                format!("{relative}/{name}")
            };
            let path = entry.path();
            let metadata = match std::fs::symlink_metadata(&path) {
                Ok(metadata) => metadata,
                Err(_) => continue,
            };
            if metadata.is_dir() {
                // `.git` and `node_modules` are never part of a build context.
                if name == ".git" || name == "node_modules" {
                    continue;
                }
                pending.push((path, child));
            } else if metadata.is_file() {
                let guest = format!("{PROJECT_DIR}/{child}");
                super::transfer::copy_in(wsl, distro, &path, &guest, root)?;
                written += 1;
            }
        }
    }
    Ok(written)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::spec::{BuildSpec, HealthcheckSpec, PortLease};

    fn web() -> ResourceSpec {
        ResourceSpec {
            name: "web".to_string(),
            kind: "app".to_string(),
            image: None,
            build: Some(BuildSpec {
                context: ".".to_string(),
                dockerfile: "Dockerfile".to_string(),
            }),
            command: vec!["node".to_string(), "server.js".to_string()],
            env: BTreeMap::from([
                (
                    "DATABASE_URL".to_string(),
                    "postgres://hello:pw@db:5432/hello".to_string(),
                ),
                ("GREETING".to_string(), "hello".to_string()),
            ]),
            ports: vec![3000],
            depends_on: vec!["db".to_string()],
            healthcheck: Some(HealthcheckSpec {
                port: 3000,
                path: Some("/health".to_string()),
                interval: "5s".to_string(),
            }),
            engine: None,
            version: None,
            volume: None,
        }
    }

    fn db() -> ResourceSpec {
        ResourceSpec {
            name: "db".to_string(),
            kind: "database".to_string(),
            image: None,
            build: None,
            command: Vec::new(),
            env: BTreeMap::from([
                ("POSTGRES_USER".to_string(), "hello".to_string()),
                ("POSTGRES_PASSWORD".to_string(), "pw".to_string()),
            ]),
            ports: Vec::new(),
            depends_on: Vec::new(),
            healthcheck: None,
            engine: Some("postgres".to_string()),
            version: Some("16".to_string()),
            volume: None,
        }
    }

    fn spec() -> EnvironmentSpec {
        let mut spec = EnvironmentSpec::new("env-1", "hello-pg");
        spec.ports.push(PortLease {
            resource: "web".to_string(),
            guest_port: 3000,
            host_port: 40001,
        });
        spec.ports.push(PortLease {
            resource: "db".to_string(),
            guest_port: 5432,
            host_port: 40002,
        });
        spec.resources.push(web());
        spec.resources.push(db());
        spec
    }

    fn rendered() -> String {
        compose_yaml(&spec()).expect("compose yaml")
    }

    #[test]
    fn the_app_is_built_from_the_projects_own_context() {
        let document = compose_document(&spec()).expect("document");
        assert_eq!(
            document["services"]["web"]["build"]["context"],
            Value::String(PROJECT_DIR.to_string())
        );
        assert_eq!(document["services"]["web"]["build"]["dockerfile"], "Dockerfile");
        assert_eq!(
            document["services"]["web"]["command"],
            serde_json::json!(["node", "server.js"]),
            "the Manifest's command is the exec form, not a shell string"
        );
    }

    #[test]
    fn a_postgres_version_maps_to_one_image() {
        assert_eq!(image_for(&db()).expect("image"), "postgres:16-alpine");
        let mut pinned = db();
        pinned.version = Some("16.4".to_string());
        assert_eq!(image_for(&pinned).expect("image"), "postgres:16.4-alpine");

        let mut other = db();
        other.engine = Some("mysql".to_string());
        assert_eq!(other.engine.as_deref(), Some("mysql"));
        let err = image_for(&other).expect_err("v0 runs postgres");
        assert_eq!(err.code(), "Unsupported");

        let mut bad = db();
        bad.version = Some("16; rm -rf /".to_string());
        assert!(image_for(&bad).is_err(), "a version is a tag, not a command");
    }

    #[test]
    fn the_database_volume_is_pinned_by_name_so_compose_cannot_prefix_it() {
        let document = compose_document(&spec()).expect("document");
        assert_eq!(
            document["volumes"]["hello-pg-db-data"]["name"],
            "hello-pg-db-data",
            "Compose would otherwise create agentify_hello-pg-db-data: {document}"
        );
        assert_eq!(
            document["services"]["db"]["volumes"][0],
            format!("hello-pg-db-data:{POSTGRES_DATA_DIR}")
        );

        let mut pinned = db();
        pinned.volume = Some("pinned-data".to_string());
        assert_eq!(volume_name("hello-pg", &pinned), "pinned-data");
    }

    #[test]
    fn depends_on_waits_for_the_databases_healthcheck() {
        let document = compose_document(&spec()).expect("document");
        assert_eq!(
            document["services"]["web"]["depends_on"]["db"]["condition"],
            "service_healthy"
        );
        assert!(
            document["services"]["db"]["healthcheck"]["test"][1]
                .as_str()
                .expect("test")
                .contains("pg_isready"),
            "the database's readiness is the engine's own client"
        );
    }

    #[test]
    fn each_lease_is_published_on_loopback_only() {
        // Compose owns the listener, and it must be loopback-only: the daemon
        // probes the lease on 127.0.0.1, and nothing reaches the LAN.
        let document = compose_document(&spec()).expect("document");
        for (service, expected) in [
            ("web", "127.0.0.1:40001:3000"),
            ("db", "127.0.0.1:40002:5432"),
        ] {
            let ports = document["services"][service]["ports"]
                .as_array()
                .unwrap_or_else(|| panic!("{service} publishes its lease: {document}"));
            assert_eq!(ports.len(), 1, "{service}: {document}");
            assert_eq!(ports[0].as_str(), Some(expected), "{service}: {document}");
        }
        let yaml = rendered();
        assert!(!yaml.contains("privileged"), "{yaml}");
        assert!(!yaml.contains("network_mode"), "{yaml}");
        assert!(!yaml.contains("/var/run/docker.sock"), "{yaml}");
    }

    #[test]
    fn a_relay_token_is_parseable_and_names_only_the_service_and_the_ports() {
        let relays = relays(&spec());
        assert_eq!(relays.len(), 2);
        assert_eq!(relays[0].token(), "db:5432:40002");
        assert_eq!(relays[1].token(), "web:3000:40001");
        for relay in &relays {
            let token = relay.token();
            let parts: Vec<&str> = token.split(':').collect();
            assert_eq!(parts.len(), 3, "{token}");
            assert!(parts[1].parse::<u16>().is_ok());
            assert!(parts[2].parse::<u16>().is_ok());
        }
    }

    #[test]
    fn a_build_context_cannot_climb_out_of_the_project() {
        assert_eq!(build_context("."), PROJECT_DIR);
        assert_eq!(build_context("./"), PROJECT_DIR);
        assert_eq!(build_context("app"), format!("{PROJECT_DIR}/app"));
        for climbing in ["..", "../../etc", "a/../../etc", "/etc"] {
            let resolved = build_context(climbing);
            assert!(
                resolved == PROJECT_DIR || resolved.starts_with(&format!("{PROJECT_DIR}/")),
                "{climbing} resolved outside the Project: {resolved}"
            );
            assert!(!resolved.contains(".."), "{climbing} → {resolved}");
        }
    }

    #[test]
    fn the_env_is_passed_through_verbatim() {
        let document = compose_document(&spec()).expect("document");
        assert_eq!(
            document["services"]["web"]["environment"]["DATABASE_URL"],
            "postgres://hello:pw@db:5432/hello"
        );
        assert_eq!(
            document["services"]["db"]["environment"]["POSTGRES_PASSWORD"],
            "pw"
        );
    }
}
